CREATE TABLE IF NOT EXISTS campus_device (
  id BIGSERIAL PRIMARY KEY,
  device_code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(128) NOT NULL,
  category VARCHAR(48) NOT NULL,
  location VARCHAR(160) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'ONLINE',
  description VARCHAR(400),
  last_seen TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS telemetry_record (
  id BIGSERIAL PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES campus_device(id) ON DELETE CASCADE,
  metric_key VARCHAR(48) NOT NULL,
  metric_value DOUBLE PRECISION NOT NULL,
  unit VARCHAR(24) NOT NULL DEFAULT '',
  recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_telemetry_device_time ON telemetry_record(device_id, recorded_at DESC);
CREATE TABLE IF NOT EXISTS campus_alarm (
  id BIGSERIAL PRIMARY KEY,
  device_id BIGINT REFERENCES campus_device(id) ON DELETE SET NULL,
  level VARCHAR(16) NOT NULL DEFAULT 'WARNING',
  title VARCHAR(160) NOT NULL,
  detail VARCHAR(500) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  acknowledged_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS control_command (
  id BIGSERIAL PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES campus_device(id) ON DELETE CASCADE,
  command_key VARCHAR(64) NOT NULL,
  command_payload VARCHAR(500) NOT NULL DEFAULT '{}',
  command_status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS operation_log (
  id BIGSERIAL PRIMARY KEY,
  actor VARCHAR(80) NOT NULL DEFAULT 'admin',
  action VARCHAR(160) NOT NULL,
  detail VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);